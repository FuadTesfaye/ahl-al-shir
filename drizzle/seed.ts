async function seed() {
  console.log('🌱 Starting seed...');

  // 1. Seed Poems
  console.log(`Clearing existing poems and inserting ${rawPoems.length} poems...`);
  await db.delete(schema.poems);

  const formattedPoems = rawPoems.map((p) => ({
    title: p.title,
    poet: p.poet,
    era: p.era,
    firstLine: p.firstLine,
    answer: p.answer,
    normalizedAnswer: normalizeArabic(p.answer),
  }));

  await db.insert(schema.poems).values(formattedPoems);
  console.log(`✅ Successfully seeded ${formattedPoems.length} poems!`);

  // 2. Seed Default Admin
  console.log('Seeding default admin user...');
  const adminPassword = 'admin123';
  const salt = bcrypt.genSaltSync(10);
  const passwordHash = bcrypt.hashSync(adminPassword, salt);

  // Upsert or insert admin
  const adminUsers = await db.select().from(schema.admins);
  if (adminUsers.length === 0) {
    await db.insert(schema.admins).values([
      {
        username: 'admin',
        email: 'admin@ahl-al-shir.com',
        passwordHash,
        role: 'super_admin',
      },
      {
        username: 'fuad',
        email: 'fuad@ahl-al-shir.com',
        passwordHash,
        role: 'super_admin',
      },
    ]);
    console.log('✅ Seeded default admins: admin / admin123 and fuad / admin123');
  } else {
    console.log(`ℹ️ Admin already exists (${adminUsers.length} admins found)`);
  }

  console.log('🎉 Seeding completed successfully!');
  process.exit(0);
}

seed().catch((err) => {
  console.error('❌ Error during seeding:', err);
  process.exit(1);
});
